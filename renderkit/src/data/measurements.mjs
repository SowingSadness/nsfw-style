/**
 * Только рендер-стадия: `postprocess`-строки в фит и в аудит рендера не попадают (A5).
 * `estimated: true` — оценка по двойнику; `suspect: true` — замер, противоречащий двойнику
 * того же конфига (ни в фит, ни в агрегат аудита не идёт, печатается отдельно).
 *
 * @param {ReadonlyArray<Measurement>} rows
 * @returns {Measurement[]}
 */
export function renderRows(rows = MEASUREMENTS) {
  return rows.filter((row) => row.stage === 'render');
}

/**
 * Строки, попадающие в фит: рендер-стадия, без пометки `≈` (оценка по двойнику) и без
 * противоречивых замеров (`suspect`).
 *
 * @param {ReadonlyArray<Measurement>} rows
 * @returns {Measurement[]}
 */
export function fitRows(rows = MEASUREMENTS) {
  return renderRows(rows).filter((row) => !row.estimated && !row.suspect);
}

/**
 * Строки, которые аудит считает в сводке: рендер-стадия без противоречивых замеров
 * (`suspect` печатается отдельным списком и в медиану/максимум не входит).
 *
 * @param {ReadonlyArray<Measurement>} rows
 * @returns {Measurement[]}
 */
export function auditedRows(rows = MEASUREMENTS) {
  return renderRows(rows).filter((row) => !row.suspect);
}
