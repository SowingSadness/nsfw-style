/**
 * Замеры, на которых калибруется модель (`tools/fit.mjs` → `src/data/model.mjs`).
 *
 * Файл заполняется **руками**: строка = один реальный прогон из наших документов. Ни одного
 * числа, которого нет в источнике. `source` — `<путь от корня репозитория>#<таблица/строка/число>`;
 * `provenance.test.mjs` проверяет, что файл по пути существует, а `audit-measurements.mjs` —
 * что модель воспроизводит замер в допуске (`tolerance` + `note` — только для тех строк, где
 * расхождение объяснимо и не лечится моделью).
 *
 * Поля строки:
 * - `id` — стабильный идентификатор (`<family>-<что меряли>`), им же пользуется аудит;
 * - `source` — файл + якорь (номер строки таблицы/литерал замера), без выдуманных ссылок;
 * - `machine` — железо, на котором снят замер (все наши — RTX 4080);
 * - `stage` — `render` (рендер-стадия, идёт в фит) или `postprocess` (отдельная стадия, в фит
 *   рендера не попадает никогда);
 * - `config` — **резолвленные** поля прогона: `model`, `vramGib`, `ramGib`, `disk`, `refs`,
 *   `aspect`, `width`, `height`, `tokens`, `steps`, `offload`, `offloadBlocks`, `kvCache`,
 *   `encoderDevice`, `windowAttnPx`, `vaeTilePx`, плюс `refPx` (сетка референсов, 0 = сетка кадра);
 * - `measured` — только снятые числа: `peakVramGib`, `loadS`, `encodeS`, `genS`, `totalS`;
 * - `note` — что в замере особенного (метрика, режим, оценка по двойнику);
 * - `tolerance` — расширение допуска аудита в процентах (только вместе с `note`);
 * - `estimated` — `true` для чисел, которые в документе помечены `≈` (в фит не идут);
 * - `suspect` — `true` для замера, который **противоречит** другому замеру того же конфига
 *   (двойник в соседней строке): в фит он не идёт, иначе тянет модель в сторону, и не входит
 *   в агрегат аудита; печатается отдельным списком с причиной в `note`.
 *
 * Метрики пиков в наших документах **разные**, и это записано в `note` там, где важно:
 * - `docs/bench/vram-tiers.md` — полное `memory.used` карты по `nvidia-smi` (включая рабочий стол
 *   ≈2 ГиБ); это «честный» ответ на вопрос «влезет ли в 16 ГиБ»;
 * - `docs/bench/presets.md` — пик **аллокатора torch** своего процесса (без рабочего стола);
 *   он занижен относительно `nvidia-smi` примерно на объём рабочего стола (в vram-tiers те же
 *   прогоны дают `свой процесс` = полное − 2.05 ГиБ);
 * - `docs/bench/kv-cache-offload.md` — `max` по `nvidia-smi` (как vram-tiers);
 * - `AGENTS.md` §4 — пики процесса из текста/`bench vram`.
 *
 * Поэтому метрика модели — `nvidia-smi` (полное `memory.used` карты): так мерили `vram-tiers.md`
 * и `kv-cache-offload.md`, и так отвечает на вопрос «влезет ли в 16 ГБ». Пики другой метрики
 * приводятся к ней **измеренной** поправкой `MODEL.coefficients.vram.measurementDesktopReserveGib`
 * (2.05 ГиБ: в `vram-tiers.md` «полное» − «свой процесс» = 2.05–2.32 ГиБ на четырёх строках) и
 * потому идут в фит наравне; аудит печатает такие строки со звёздочкой.
 */

