/**
 * Чем мерили пик VRAM — по источнику (документы мерили разными способами, см. шапку файла):
 * `nvidia-smi` — полное `memory.used` карты; `torch-allocator` — пик аллокатора своего процесса;
 * `process` — пик процесса из текста/`bench vram`. Строка может переопределить это полем
 * `peakMetric` (единственный случай сейчас — 1080p из §4, где в документе есть оба числа).
 */
export const PEAK_METRICS = Object.freeze({
  'docs/bench/vram-tiers.md': 'nvidia-smi',
  'docs/bench/kv-cache-offload.md': 'nvidia-smi',
  'docs/bench/presets.md': 'torch-allocator',
  'AGENTS.md': 'process',
});

/**
 * Файл источника без якоря: `docs/bench/presets.md#…` → `docs/bench/presets.md`.
 *
 * @param {string} source
 * @returns {string}
 */
export function sourceFile(source) {
  const index = source.indexOf('#');
  return index === -1 ? source : source.slice(0, index);
}

/**
 * Метрика пика для строки: явное поле важнее таблицы по файлу.
 *
 * @param {Measurement} row
 * @returns {'nvidia-smi' | 'torch-allocator' | 'process' | null}
 */
export function peakMetricOf(row) {
  if (row.peakMetric) return row.peakMetric;
  const file = sourceFile(row.source);
  const metric = /** @type {Record<string, 'nvidia-smi' | 'torch-allocator' | 'process'>} */ (PEAK_METRICS)[file];
  return metric ?? null;
}

